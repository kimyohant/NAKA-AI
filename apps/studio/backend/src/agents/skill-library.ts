export function renderLibrarySkill(entry: LibrarySkill): string {
  const name = entry.id.split('/').at(-1)
  return `---\nname: ${name}\ndescription: ${entry.description}\n---\n\n# ${entry.title}\n\n${entry.rules.map(rule => `- ${rule}`).join('\n')}\n`
}
