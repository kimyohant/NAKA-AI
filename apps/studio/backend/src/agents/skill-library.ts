/** Optional, original production skills. Installing one creates a normal agent SKILL.md. */
export type SkillCategory = 'story' | 'continuity' | 'cinematography' | 'visual' | 'quality'
export type SkillAgent = 'script_rewriter' | 'extractor' | 'storyboard_breaker' | 'prompt_generator'

export interface LibrarySkill {
  id: string
  agent: SkillAgent
  category: SkillCategory
  title: string
  titleTh: string
  description: string
  descriptionTh: string
  rules: string[]
}

function skill(agent: SkillAgent, category: SkillCategory, parent: string, slug: string,
  title: string, titleTh: string, description: string, descriptionTh: string, ...rules: string[]): LibrarySkill {
  return { id: `${parent}/${slug}`, agent, category, title, titleTh, description, descriptionTh, rules }
}

